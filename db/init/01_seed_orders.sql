-- Runs automatically on the first creation of the Docker PostgreSQL volume.
-- The table intentionally starts WITHOUT a secondary index on customer_id/status.
CREATE TABLE orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT NOT NULL,
    status       VARCHAR(20) NOT NULL
                 CHECK (status IN ('PAID', 'CREATED', 'CANCELLED', 'REFUNDED')),
    created_at   TIMESTAMP NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL
);

-- Create 1,000,000 reproducible rows. The customer/status distribution is
-- intentionally mixed so that each customer has only a small number of rows.
INSERT INTO orders (id, customer_id, status, created_at, total_amount)
SELECT
    g,
    ((g * 7919) % 100003) + 1,
    CASE (g % 4)
        WHEN 0 THEN 'PAID'
        WHEN 1 THEN 'CREATED'
        WHEN 2 THEN 'CANCELLED'
        ELSE 'REFUNDED'
    END,
    TIMESTAMP '2025-01-01 00:00:00'
        + ((g % 31536000)::double precision * INTERVAL '1 second'),
    ROUND((10 + RANDOM() * 4990)::NUMERIC, 2)
FROM generate_series(1::BIGINT, 1000000::BIGINT) AS g;

-- Keep the identity sequence ahead of the explicit IDs above.
SELECT setval(pg_get_serial_sequence('orders', 'id'), (SELECT MAX(id) FROM orders));
ANALYZE orders;
